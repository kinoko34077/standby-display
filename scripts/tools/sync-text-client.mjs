import { cp, mkdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { spawn } from "node:child_process";

const standbyRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const vendorPath = path.join(standbyRoot, "vendor", "text-transform.mjs");
const vendorHashPath = path.join(standbyRoot, "vendor", "text-transform.mjs.sha256");
const fallbackPath = path.join(standbyRoot, "vendor", "kanji-fallback.mjs");
const fallbackHashPath = path.join(standbyRoot, "vendor", "kanji-fallback.mjs.sha256");
const sourceSelection = resolveSourceRoot(process.argv.slice(2));
const sourceRoot = sourceSelection.root;
const checkOnly = process.argv.includes("--check");

const generatorPath = path.join(sourceRoot, "scripts", "generate-text-client.mjs");
const fallbackGeneratorPath = path.join(sourceRoot, "scripts", "generate-kanji-fallback.mjs");
const sourceAvailable = await pathExists(generatorPath) && await pathExists(fallbackGeneratorPath);

if (!sourceAvailable) {
  if (sourceSelection.explicit) {
    throw new Error(`Canonical source repo is unavailable: ${sourceRoot}`);
  }

  if (!checkOnly) {
    throw new Error(`Canonical source repo is unavailable: ${sourceRoot}`);
  }

  const vendor = await readArtifact(vendorPath, "Vendor text client");
  const fallback = await readArtifact(fallbackPath, "Vendor kanji fallback");
  const recordedHash = await readRecordedHash(vendorHashPath);
  const fallbackRecordedHash = await readRecordedHash(fallbackHashPath);
  const actualHash = hashText(vendor);
  const fallbackActualHash = hashText(fallback);
  if (!vendor.startsWith("// Generated by scripts/build-text-client.mjs.")) {
    console.error(`Vendor text client is missing a generated header: ${path.relative(standbyRoot, vendorPath)}`);
    process.exitCode = 1;
  } else if (!recordedHash || recordedHash !== actualHash) {
    console.error(`Vendor text client hash does not match ${path.relative(standbyRoot, vendorHashPath)}`);
    process.exitCode = 1;
  } else if (!fallback.startsWith("// Generated by scripts/build-kanji-fallback.mjs.")) {
    console.error(`Vendor kanji fallback is missing a generated header: ${path.relative(standbyRoot, fallbackPath)}`);
    process.exitCode = 1;
  } else if (!fallbackRecordedHash || fallbackRecordedHash !== fallbackActualHash) {
    console.error(`Vendor kanji fallback hash does not match ${path.relative(standbyRoot, fallbackHashPath)}`);
    process.exitCode = 1;
  } else {
    console.warn("Canonical source unavailable; verified the recorded vendored client hash.");
  }
} else {
  const { generateTextClientSource } = await import(pathToFileURL(generatorPath).href);
  const { generateKanjiFallbackSource } = await import(pathToFileURL(fallbackGeneratorPath).href);
  const expected = await generateTextClientSource(sourceRoot);
  const expectedFallback = await generateKanjiFallbackSource(sourceRoot);

  if (checkOnly) {
    const actual = await readArtifact(vendorPath, "Vendor text client");
    const actualFallback = await readArtifact(fallbackPath, "Vendor kanji fallback");
    const recordedHash = await readRecordedHash(vendorHashPath);
    const fallbackRecordedHash = await readRecordedHash(fallbackHashPath);
    const actualHash = hashText(actual);
    const actualFallbackHash = hashText(actualFallback);
    if (actual !== expected || recordedHash !== actualHash || actualFallback !== expectedFallback || fallbackRecordedHash !== actualFallbackHash) {
      console.error(`Vendor text client is stale: ${path.relative(standbyRoot, vendorPath)}`);
      console.error("Run `npm run sync:text-client` and review the generated client/fallback diff and hashes.");
      process.exitCode = 1;
    } else {
      console.log("Vendor text client is up to date.");
    }
  } else {
    await runNode(path.join(sourceRoot, "scripts", "build-text-client.mjs"), sourceRoot);
    await runNode(path.join(sourceRoot, "scripts", "build-kanji-fallback.mjs"), sourceRoot);
    await mkdir(path.dirname(vendorPath), { recursive: true });
    await cp(path.join(sourceRoot, "dist", "text-transform.mjs"), vendorPath);
    await cp(path.join(sourceRoot, "dist", "kanji-fallback.mjs"), fallbackPath);
    await writeRecordedHash(vendorPath, vendorHashPath);
    await writeRecordedHash(fallbackPath, fallbackHashPath);
    console.log(`Synced ${path.relative(standbyRoot, vendorPath)} from ${path.relative(standbyRoot, sourceRoot)}`);
  }
}

async function pathExists(filePath) {
  try {
    await readFile(filePath, "utf8");
    return true;
  } catch (error) {
    if (error?.code === "ENOENT") return false;
    throw error;
  }
}

async function readArtifact(filePath, label) {
  try {
    return await readFile(filePath, "utf8");
  } catch (error) {
    if (error?.code === "ENOENT") {
      console.error(`${label} is missing: ${path.relative(standbyRoot, filePath)}`);
      process.exitCode = 1;
      return "";
    }
    throw error;
  }
}

async function readRecordedHash(filePath) {
  try {
    return (await readFile(filePath, "utf8")).trim();
  } catch (error) {
    if (error?.code === "ENOENT") return "";
    throw error;
  }
}

async function writeRecordedHash(filePath, hashPath) {
  await mkdir(path.dirname(hashPath), { recursive: true });
  await writeFile(hashPath, `${hashText(await readFile(filePath, "utf8"))}\n`, "utf8");
}

function hashText(value) {
  return createHash("sha256").update(value).digest("hex");
}

function resolveSourceRoot(args) {
  const sourceIndex = args.indexOf("--source");
  const explicit = sourceIndex >= 0 ? args[sourceIndex + 1] : undefined;
  if (sourceIndex >= 0 && !explicit) {
    throw new Error("--source requires a directory path");
  }

  const configured = explicit || process.env.KINOTCH_API_DIR;
  return {
    root: path.resolve(standbyRoot, configured || "../kinotch-api"),
    explicit: Boolean(explicit || process.env.KINOTCH_API_DIR),
  };
}

function runNode(scriptPath, cwd) {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [scriptPath], { cwd, stdio: "inherit" });
    child.once("error", reject);
    child.once("exit", (code, signal) => {
      if (code === 0) {
        resolve();
        return;
      }
      reject(new Error(`Text client generation failed (${code ?? signal})`));
    });
  });
}
